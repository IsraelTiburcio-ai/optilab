import {readFileSync,writeFileSync} from 'node:fs';
const base=readFileSync('firestore.rules','utf8'),start=base.indexOf('    match /users/{uid} {'),end=base.indexOf('    function course(c) {');
if(start<0||end<start)throw Error('Review Rules structure before generating production access');
const admission=`    // General production: verified account ownership, never a pilot allowlist.
    // Optional emergency control has no leases or scheduled activation window.
    function productionAccess(uid,write) {
      let control=/databases/$(database)/documents/syncProductionControl/current;
      let erased=/databases/$(database)/documents/syncPilotMembers/$(uid);
      return owner(uid) && request.auth.token.email_verified == true
        && (!exists(erased) || get(erased).data.status != 'erased')
        && (!exists(control) || (exact(get(control).data,['version','readsEnabled','writesEnabled'])
          && get(control).data.version == 1 && get(control).data.readsEnabled == true
          && (!write || get(control).data.writesEnabled == true)));
    }
`;
const users=base.slice(start,end).replace(/allow ([^:]+): if owner\(uid\)/g,(_m,verbs)=>`allow ${verbs}: if productionAccess(uid,${/create|update|delete|write/.test(verbs)})`);
const result='// GENERATED by scripts/build-production-rules.mjs.\n'+base.slice(0,start)+admission+users+base.slice(end);
if(process.argv.includes('--write'))writeFileSync('firestore.production.rules',result);else if(readFileSync('firestore.production.rules','utf8')!==result)throw Error('Production Rules out of date');
