import {readFileSync,writeFileSync} from 'node:fs';
const base=readFileSync('firestore.rules','utf8');
const start=base.indexOf('    match /users/{uid} {'),end=base.indexOf('    function course(c) {');
if(start<0||end<start)throw Error('Rules structure changed; review generator');
const admission=`    // Administrative grant/config documents are never client writable.
    function pilotAccess(uid,write) {
      let config=get(/databases/$(database)/documents/syncPilotControl/current).data;
      let grant=get(/databases/$(database)/documents/syncPilotMembers/$(uid)).data;
      return owner(uid) && request.auth.token.email_verified == true
        && config.version == 1 && config.expiresAt is timestamp && config.expiresAt > request.time
        && config.readsEnabled == true && (!write || config.writesEnabled == true)
        && grant.version == 1 && grant.uid == uid && grant.status == 'active'
        && grant.expiresAt is timestamp && grant.expiresAt > request.time;
    }
    match /syncPilotControl/{document} {
      allow get: if signedIn() && request.auth.token.email_verified == true && document == 'current';
      allow list,write: if false;
    }
    match /syncPilotMembers/{uid} {
      allow get: if owner(uid) && request.auth.token.email_verified == true;
      allow list,write: if false;
    }
    match /syncPilotAudit/{document} { allow read,write: if false; }
`;
const privateRules=base.slice(start,end).replace(/allow ([^:]+): if owner\(uid\)/g,(_match,verbs)=>`allow ${verbs}: if pilotAccess(uid,${/create|update|delete|write/.test(verbs)})`);
const result='// GENERATED by scripts/build-pilot-rules.mjs from reviewed base rules.\n'+base.slice(0,start)+admission+privateRules+base.slice(end);
if(process.argv.includes('--write'))writeFileSync('firestore.pilot.rules',result);else if(readFileSync('firestore.pilot.rules','utf8')!==result)throw Error('Pilot Rules out of date');
